import type { SendEmailAttachment, SendEmailRequest, SendEmailResponse } from "@/types";
import { decodeBase64ToBytes } from "@/utils/attachments";
import { type EmailProvider, EmailProviderError } from "./types";

/**
 * Cloudflare Email Service (Email Sending) provider.
 *
 * Uses the native `send_email` Workers binding — no API key, no outbound HTTP.
 * Only domains on Cloudflare DNS can send; other domains use SMTP (SMTP_ACCOUNTS_JSON).
 *
 * Constraints that differ from the Postmark path (see callers):
 * - total message size 5 MiB (attachment tiering is handled upstream)
 * - `Message-ID` is generated by Cloudflare and rejected if supplied
 * - `In-Reply-To` / `References` ARE allowlisted, so threading survives
 */

/**
 * Headers Cloudflare generates itself — supplying any of these is a hard
 * rejection by the binding, so filter rather than forward.
 * See developers.cloudflare.com/email-service/reference/headers/
 */
const RESERVED_HEADERS = new Set([
	"from",
	"to",
	"cc",
	"bcc",
	"subject",
	"reply-to",
	"message-id",
	"date",
	"mime-version",
	"content-type",
	"content-transfer-encoding",
	"dkim-signature",
	"return-path",
	"received",
	"feedback-id",
	"sender",
	"bounces-to",
	"errors-to",
]);

/** Header families the platform owns wholesale. */
const RESERVED_PREFIXES = ["arc-", "x-cloudflare-", "x-cf-"];

/** Total encoded message budget. CF caps the whole message at 5 MiB; leave
 *  headroom for MIME framing, headers and the body. */
const MAX_MESSAGE_BYTES = 4.5 * 1024 * 1024;

function normalizeAddressList(value?: string | string[]): string[] {
	if (!value) return [];
	return (Array.isArray(value) ? value : [value]).map((item) => item.trim()).filter(Boolean);
}

/** Accepts "Name <a@b>" or a bare address and returns the binding's address shape. */
function toAddress(value: string): string | EmailAddress {
	const match = value.match(/^\s*(.*?)\s*<([^>]+)>\s*$/);
	if (!match) return value.trim();

	const name = match[1].replace(/^"(.*)"$/, "$1").trim();
	const email = match[2].trim();
	return name ? { name, email } : email;
}

function buildHeaders(headers?: Record<string, string>): Record<string, string> | undefined {
	if (!headers) return undefined;

	const out: Record<string, string> = {};
	for (const [rawName, rawValue] of Object.entries(headers)) {
		// Trim first: " Message-ID " would otherwise slip past the reserved set,
		// and " In-Reply-To " would be emitted as an invalid header name.
		const name = typeof rawName === "string" ? rawName.trim() : "";
		const value = typeof rawValue === "string" ? rawValue.trim() : "";
		if (!name || !value) continue;

		const lower = name.toLowerCase();
		if (RESERVED_HEADERS.has(lower)) continue;
		if (RESERVED_PREFIXES.some((prefix) => lower.startsWith(prefix))) continue;

		out[name] = value;
	}

	return Object.keys(out).length > 0 ? out : undefined;
}

/**
 * `EmailAttachment` is a discriminated union: 'inline' REQUIRES contentId,
 * 'attachment' requires it to be absent. MailClaw's shape allows a content_id
 * without a disposition, so normalize rather than pass through.
 *
 * The binding takes RAW BYTES, not base64 (unlike the REST API and unlike
 * Postmark) — passing the base64 string straight through corrupts binaries.
 */
function buildAttachments(attachments?: SendEmailAttachment[]): EmailAttachment[] | undefined {
	if (!attachments || attachments.length === 0) return undefined;

	return attachments.map((attachment) => {
		let content: Uint8Array;
		try {
			content = decodeBase64ToBytes(attachment.content_base64);
		} catch {
			throw new EmailProviderError(`Attachment ${attachment.filename} has invalid base64 content`, {
				status: 400,
				code: "INVALID_ATTACHMENT",
			});
		}

		// A content_id means the sender intends an inline part, so treat it as
		// inline whenever present rather than dropping the id (which renders
		// embedded images broken). Do NOT reject content_id + "attachment":
		// draft staging stores every attachment as disposition "attachment", so
		// rejecting that contradiction breaks any draft carrying an inline image
		// while the identical direct send succeeds.
		if (attachment.disposition === "inline" && !attachment.content_id) {
			throw new EmailProviderError(
				`Inline attachment ${attachment.filename} requires a content_id`,
				{ status: 400, code: "INVALID_ATTACHMENT" },
			);
		}

		if (attachment.content_id) {
			return {
				disposition: "inline" as const,
				contentId: attachment.content_id,
				filename: attachment.filename,
				type: attachment.content_type,
				content,
			};
		}

		return {
			disposition: "attachment" as const,
			filename: attachment.filename,
			type: attachment.content_type,
			content,
		};
	});
}

/** Map binding failures onto the status codes the send route already understands. */
function toProviderError(error: unknown): EmailProviderError {
	const message = error instanceof Error ? error.message : String(error);
	const code = (error as { code?: string })?.code;
	const haystack = `${code ?? ""} ${message}`.toLowerCase();

	let status = 502;
	if (haystack.includes("quota") || haystack.includes("rate") || haystack.includes("429")) {
		status = 429;
	} else if (
		haystack.includes("not_allowed") ||
		haystack.includes("invalid") ||
		haystack.includes("size") ||
		haystack.includes("suppress") ||
		haystack.includes("sender")
	) {
		status = 400;
	}

	return new EmailProviderError(`Cloudflare Email Service error: ${message}`, {
		status,
		code: code ?? "CLOUDFLARE_SEND_FAILED",
		details: { code, message },
	});
}

export class CloudflareProvider implements EmailProvider {
	readonly name = "cloudflare";

	constructor(private readonly binding: SendEmail) {}

	async send(request: SendEmailRequest): Promise<SendEmailResponse> {
		const to = normalizeAddressList(request.to);
		if (to.length === 0) {
			throw new EmailProviderError("At least one recipient is required", {
				status: 400,
				code: "INVALID_RECIPIENT",
			});
		}

		if (
			to.length +
				normalizeAddressList(request.cc).length +
				normalizeAddressList(request.bcc).length >
			50
		) {
			throw new EmailProviderError("Cloudflare allows at most 50 recipients per message", {
				status: 400,
				code: "TOO_MANY_RECIPIENTS",
			});
		}

		// Estimate the size ON THE WIRE, not the raw payload: attachments are
		// re-encoded to base64 (4/3) with line breaks, and a UTF-8 body can be
		// several bytes per character. Counting raw bytes let a 3.4 MiB file plus
		// a large body slip past this check and get rejected by Cloudflare.
		const attachmentWireBytes = (request.attachments ?? []).reduce((total, item) => {
			const rawBytes = Math.ceil((item.content_base64?.length ?? 0) * 0.75);
			const base64Bytes = Math.ceil(rawBytes / 3) * 4;
			return total + base64Bytes + Math.ceil(base64Bytes / 76) + 256; // CRLFs + part headers
		}, 0);
		const encoder = new TextEncoder();
		const bodyWireBytes =
			encoder.encode(request.html ?? "").length + encoder.encode(request.text ?? "").length;
		if (attachmentWireBytes + bodyWireBytes + 2048 > MAX_MESSAGE_BYTES) {
			throw new EmailProviderError(
				"Message exceeds the Cloudflare 5 MiB total size limit; attach via link instead",
				{ status: 400, code: "MESSAGE_TOO_LARGE" },
			);
		}

		const cc = normalizeAddressList(request.cc);
		const bcc = normalizeAddressList(request.bcc);
		// The binding takes a single reply-to; validation already caps this at one.
		const replyTo = normalizeAddressList(request.reply_to)[0];
		const headers = buildHeaders(request.headers);
		const attachments = buildAttachments(request.attachments);

		// Recipients stay plain strings: the binding types them `string | string[]`,
		// and validation currently rejects display names anyway. Only `from` and
		// `replyTo` accept the {name,email} shape.
		const payload = {
			from: toAddress(request.from),
			to,
			subject: request.subject,
			...(request.html ? { html: request.html } : {}),
			...(request.text ? { text: request.text } : {}),
			...(cc.length > 0 ? { cc } : {}),
			...(bcc.length > 0 ? { bcc } : {}),
			...(replyTo ? { replyTo: toAddress(replyTo) } : {}),
			...(headers ? { headers } : {}),
			...(attachments ? { attachments } : {}),
		};

		let result: EmailSendResult;
		try {
			result = await this.binding.send(payload as Parameters<SendEmail["send"]>[0]);
		} catch (error) {
			throw toProviderError(error);
		}

		const id = (result as { messageId?: string })?.messageId;
		if (!id) {
			throw new EmailProviderError("Cloudflare Email Service returned no message id", {
				status: 502,
				code: "CLOUDFLARE_NO_MESSAGE_ID",
			});
		}

		return { id, provider: this.name };
	}
}
